CREATE EXTENSION IF NOT EXISTS postgis;
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id),
  full_name TEXT NOT NULL,
  gender VARCHAR(10) CHECK (gender IN ('male', 'female', 'other')),
  bio TEXT,
  avatar_url TEXT,
  interests TEXT[],
  preferences_vector vector(1536), -- Generated by text-embedding-3-small based on bio and interests
  is_verified BOOLEAN DEFAULT false, -- For the Blue Tick verification badge
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE plans (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  host_id UUID REFERENCES profiles(id) NOT NULL,
  title TEXT NOT NULL,
  category VARCHAR(50) NOT NULL,
  description TEXT,
  venue_name TEXT NOT NULL,
  geom geography(Point, 4326) NOT NULL, -- PostGIS coordinate
  scheduled_at TIMESTAMPTZ NOT NULL,
  max_capacity INT DEFAULT 2 CHECK (max_capacity >= 1),
  gender_reach VARCHAR(10) DEFAULT 'all' CHECK (gender_reach IN ('all', 'same')),
  status VARCHAR(20) DEFAULT 'active' CHECK (status IN ('active', 'cancelled', 'completed')),
  embedding_vector vector(1536), -- Generated from plan description and title
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Spatial index for fast proximity lookups
CREATE INDEX plans_geom_idx ON plans USING GIST (geom);
-- Vector index for fast semantic matching
CREATE INDEX plans_embedding_idx ON plans USING hnsw (embedding_vector vector_cosine_ops);

CREATE TABLE plan_participants (
  plan_id UUID REFERENCES plans(id) ON DELETE CASCADE,
  user_id UUID REFERENCES profiles(id) ON DELETE CASCADE,
  status VARCHAR(20) DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'checked_in')),
  joined_at TIMESTAMPTZ DEFAULT NOW(),
  PRIMARY KEY (plan_id, user_id)
);

CREATE TABLE chat_rooms (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  plan_id UUID REFERENCES plans(id) ON DELETE CASCADE UNIQUE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE messages (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  room_id UUID REFERENCES chat_rooms(id) ON DELETE CASCADE,
  sender_id UUID REFERENCES profiles(id),
  content TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE plans ENABLE ROW LEVEL SECURITY;
ALTER TABLE plan_participants ENABLE ROW LEVEL SECURITY;
ALTER TABLE chat_rooms ENABLE ROW LEVEL SECURITY;
ALTER TABLE messages ENABLE ROW LEVEL SECURITY;

-- Plans: Visible to all if reach is 'all', or only to matching gender if 'same'
CREATE POLICY "View Plans Policy" ON plans FOR SELECT
USING (
  status = 'active' AND (
    gender_reach = 'all' OR 
    (gender_reach = 'same' AND host_id IN (
      SELECT id FROM profiles WHERE gender = (SELECT gender FROM profiles WHERE id = auth.uid())
    ))
  )
);

-- Chat: Only approved participants can read/write messages
CREATE POLICY "Chat Access Policy" ON messages FOR ALL
USING (
  EXISTS (
    SELECT 1 FROM plan_participants pp 
    JOIN chat_rooms cr ON pp.plan_id = cr.plan_id
    WHERE cr.id = messages.room_id 
    AND pp.user_id = auth.uid() 
    AND pp.status IN ('approved', 'checked_in')
  )
);

-- ==========================================
-- AUDIT TRAIL (Change Data Capture)
-- ==========================================

CREATE SCHEMA IF NOT EXISTS audit;

CREATE TABLE audit.record_version (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    table_name TEXT NOT NULL,
    record_id UUID,
    action VARCHAR(10) CHECK (action IN ('INSERT', 'UPDATE', 'DELETE')),
    old_data JSONB,
    new_data JSONB,
    changed_by UUID,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE audit.record_version ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION audit.if_modified_func() RETURNS TRIGGER AS $body$
DECLARE
    v_old_data JSONB;
    v_new_data JSONB;
    v_record_id UUID;
BEGIN
    IF (TG_OP = 'UPDATE') THEN
        v_old_data := to_jsonb(OLD);
        v_new_data := to_jsonb(NEW);
        -- Coalesce in case table uses composite keys or non-id primary keys (we try to extract 'id' or fallback to null)
        v_record_id := (v_new_data->>'id')::UUID;
        INSERT INTO audit.record_version (table_name, record_id, action, old_data, new_data, changed_by)
        VALUES (TG_TABLE_NAME::TEXT, v_record_id, TG_OP, v_old_data, v_new_data, auth.uid());
        RETURN NEW;
    ELSIF (TG_OP = 'DELETE') THEN
        v_old_data := to_jsonb(OLD);
        v_record_id := (v_old_data->>'id')::UUID;
        INSERT INTO audit.record_version (table_name, record_id, action, old_data, changed_by)
        VALUES (TG_TABLE_NAME::TEXT, v_record_id, TG_OP, v_old_data, auth.uid());
        RETURN OLD;
    ELSIF (TG_OP = 'INSERT') THEN
        v_new_data := to_jsonb(NEW);
        v_record_id := (v_new_data->>'id')::UUID;
        INSERT INTO audit.record_version (table_name, record_id, action, new_data, changed_by)
        VALUES (TG_TABLE_NAME::TEXT, v_record_id, TG_OP, v_new_data, auth.uid());
        RETURN NEW;
    END IF;
    RETURN NULL;
END;
$body$
LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER audit_profiles_trigger
AFTER INSERT OR UPDATE OR DELETE ON profiles
FOR EACH ROW EXECUTE FUNCTION audit.if_modified_func();

CREATE TRIGGER audit_plans_trigger
AFTER INSERT OR UPDATE OR DELETE ON plans
FOR EACH ROW EXECUTE FUNCTION audit.if_modified_func();
